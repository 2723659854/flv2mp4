            $this->refYPlane = null;
            $this->refUPlane = null;
            $this->refVPlane = null;
            $this->frameNum = 0;
            $this->idrPicId++;
            $this->poc = 0;

            $nalUnits[] = $this->generateSPS();
            $nalUnits[] = $this->generatePPS();
        }
        $sliceData = $this->encodeSlice($yuvData, $isKeyframe);
        $nalUnits[] = $sliceData;
        return $nalUnits;
    }











