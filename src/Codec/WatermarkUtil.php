    /**
     * 生成文字水印 YUV 文件
     * @param string $text 文字内容
     * @param int $width 水印宽度
     * @param int $height 水印高度
     * @param string $outputFile 输出YUV文件路径
     * @param array $options 可选配置：fontSize, fontColor, bgColor, fontFamily
     * @return bool
     * @throws \RuntimeException
     */
    public static function generateTextWatermark(
        string $text,
        int $width,
        int $height,
        string $outputFile,
        array $options = []
    ): bool {
        $fontColor = $options['fontColor'] ?? [255, 255, 255];
        $bgColor = $options['bgColor'] ?? [0, 0, 0];

        if (extension_loaded('gd')) {
            return self::generateWithGd($text, $width, $height, $outputFile, $options);
        }

        return self::generateWithDotMatrix($text, $width, $height, $outputFile, $fontColor, $bgColor);
    }

    private static function generateWithGd(
        string $text,
        int $width,
        int $height,
        string $outputFile,
        array $options
    ): bool {
        $fontSize = $options['fontSize'] ?? 12;
        $fontColor = $options['fontColor'] ?? [255, 255, 255];
        $bgColor = $options['bgColor'] ?? [0, 0, 0];
        $fontFamily = $options['fontFamily'] ?? null;

        $img = imagecreatetruecolor($width, $height);
        if ($img === false) {
            throw new \RuntimeException('创建图像失败');
        }

        $bg = imagecolorallocate($img, $bgColor[0], $bgColor[1], $bgColor[2]);
        imagefilledrectangle($img, 0, 0, $width - 1, $height - 1, $bg);

        $textColor = imagecolorallocate($img, $fontColor[0], $fontColor[1], $fontColor[2]);

        if ($fontFamily && file_exists($fontFamily)) {
            $bbox = imagettfbbox($fontSize, 0, $fontFamily, $text);
            if ($bbox === false) {
                imagedestroy($img);
                throw new \RuntimeException('计算文字尺寸失败');
            }
            $textW = $bbox[2] - $bbox[0];
            $textH = $bbox[1] - $bbox[7];
            $x = (int)(($width - $textW) / 2) - $bbox[0];
            $y = (int)(($height - $textH) / 2) - $bbox[7];
            imagettftext($img, $fontSize, 0, $x, $y, $textColor, $fontFamily, $text);
        } else {
            $fontWidth = imagefontwidth($fontSize);
            $fontHeight = imagefontheight($fontSize);
            $textW = $fontWidth * strlen($text);
            $x = (int)(($width - $textW) / 2);
            $y = (int)(($height - $fontHeight) / 2);
            imagestring($img, $fontSize, $x, $y, $text, $textColor);
        }

        $yuvData = self::rgbImageToYuv420p($img, $width, $height);
        imagedestroy($img);

        $result = file_put_contents($outputFile, $yuvData);
        return $result !== false;
    }

    private static function generateWithDotMatrix(
        string $text,
        int $width,
        int $height,
        string $outputFile,
        array $fontColor,
        array $bgColor
    ): bool {
        $charHeight = 16;
        $textLen = strlen($text);

        $charWidth = 8;
        $charSpacing = 1;
        $totalCharWidth = $charWidth + $charSpacing;
        $textWidth = $textLen * $totalCharWidth - $charSpacing;

        $compactMode = false;
        if ($textWidth > $width) {
            $compactMode = true;
            $charWidth = 7;
            $charSpacing = 0;
            $totalCharWidth = $charWidth + $charSpacing;
            $textWidth = $textLen * $totalCharWidth - $charSpacing;
        }

        $startX = max(0, (int)(($width - $textWidth) / 2));
        $startY = max(0, (int)(($height - $charHeight) / 2));

        $ySize = $width * $height;
        $uvSize = $ySize >> 2;
        $yuv = str_repeat("\x00", $ySize + $uvSize * 2);

        $bgY = (int)(0.299 * $bgColor[0] + 0.587 * $bgColor[1] + 0.114 * $bgColor[2]);
        $bgU = (int)(-0.14713 * $bgColor[0] - 0.28886 * $bgColor[1] + 0.436 * $bgColor[2] + 128);
        $bgV = (int)(0.615 * $bgColor[0] - 0.51499 * $bgColor[1] - 0.10001 * $bgColor[2] + 128);

        $fgY = (int)(0.299 * $fontColor[0] + 0.587 * $fontColor[1] + 0.114 * $fontColor[2]);
        $fgU = (int)(-0.14713 * $fontColor[0] - 0.28886 * $fontColor[1] + 0.436 * $fontColor[2] + 128);
        $fgV = (int)(0.615 * $fontColor[0] - 0.51499 * $fontColor[1] - 0.10001 * $fontColor[2] + 128);

        $bgY = max(0, min(255, $bgY));
        $bgU = max(0, min(255, $bgU));
        $bgV = max(0, min(255, $bgV));
        $fgY = max(0, min(255, $fgY));
        $fgU = max(0, min(255, $fgU));
        $fgV = max(0, min(255, $fgV));

        for ($y = 0; $y < $height; $y++) {
            for ($x = 0; $x < $width; $x++) {
                $yuv[$y * $width + $x] = chr($bgY);
            }
        }

        $uOffset = $ySize;
        $vOffset = $ySize + $uvSize;
        for ($i = 0; $i < $uvSize; $i++) {
            $yuv[$uOffset + $i] = chr($bgU);
            $yuv[$vOffset + $i] = chr($bgV);
        }

        $fgPixelMap = [];

        for ($i = 0; $i < $textLen; $i++) {
            $char = $text[$i];
            $glyph = self::$font8x16[$char] ?? self::$font8x16[' '];
            $charX = $startX + $i * $totalCharWidth;

            for ($row = 0; $row < $charHeight; $row++) {
                $pixelY = $startY + $row;
                if ($pixelY < 0 || $pixelY >= $height) continue;

                $rowData = $glyph[$row];
                $bitOffset = $compactMode ? 6 : 7;
                for ($col = 0; $col < $charWidth; $col++) {
                    $pixelX = $charX + $col;
                    if ($pixelX < 0 || $pixelX >= $width) continue;

                    if (($rowData >> ($bitOffset - $col)) & 0x01) {
                        $yuv[$pixelY * $width + $pixelX] = chr($fgY);
                        $fgPixelMap[$pixelY][$pixelX] = true;
                    }
                }
            }
        }

        foreach ($fgPixelMap as $py => $xs) {
            foreach ($xs as $px => $_) {
                $uvX = $px >> 1;
                $uvY = $py >> 1;
                $uvIdx = $uvY * ($width >> 1) + $uvX;
                if ($uvIdx >= 0 && $uvIdx < $uvSize) {
                    $yuv[$uOffset + $uvIdx] = chr($fgU);
                    $yuv[$vOffset + $uvIdx] = chr($fgV);
                }
            }
        }

        $result = file_put_contents($outputFile, $yuv);
        return $result !== false;
    }

    /**
     * RGB图像转YUV420p
     * @param \GdImage $img GD图像
     * @param int $width 宽度
     * @param int $height 高度
     * @return string
     */
    private static function rgbImageToYuv420p($img, int $width, int $height): string
    {
        $ySize = $width * $height;
        $uvSize = $ySize >> 2;
        $yuv = str_repeat("\x00", $ySize + $uvSize * 2);

        $uOffset = $ySize;
        $vOffset = $ySize + $uvSize;

        $uBuffer = array_fill(0, $uvSize, 0);
        $vBuffer = array_fill(0, $uvSize, 0);
        $uvCount = array_fill(0, $uvSize, 0);

        for ($y = 0; $y < $height; $y++) {
            for ($x = 0; $x < $width; $x++) {
                $rgb = imagecolorat($img, $x, $y);
                $r = ($rgb >> 16) & 0xFF;
                $g = ($rgb >> 8) & 0xFF;
                $b = $rgb & 0xFF;

                $yVal = (int)(0.299 * $r + 0.587 * $g + 0.114 * $b);
                $uVal = (int)(-0.14713 * $r - 0.28886 * $g + 0.436 * $b + 128);
                $vVal = (int)(0.615 * $r - 0.51499 * $g - 0.10001 * $b + 128);

                $yVal = max(0, min(255, $yVal));
                $uVal = max(0, min(255, $uVal));
                $vVal = max(0, min(255, $vVal));

                $yuv[$y * $width + $x] = chr($yVal);

                $uvX = $x >> 1;
                $uvY = $y >> 1;
                $uvIdx = $uvY * ($width >> 1) + $uvX;
                $uBuffer[$uvIdx] += $uVal;
                $vBuffer[$uvIdx] += $vVal;
                $uvCount[$uvIdx]++;
            }
        }

        for ($i = 0; $i < $uvSize; $i++) {
            $count = $uvCount[$i] > 0 ? $uvCount[$i] : 1;
            $uAvg = (int)($uBuffer[$i] / $count);
            $vAvg = (int)($vBuffer[$i] / $count);
            $yuv[$uOffset + $i] = chr(max(0, min(255, $uAvg)));
            $yuv[$vOffset + $i] = chr(max(0, min(255, $vAvg)));
        }

        return $yuv;
    }

    /**
     * 从图片文件生成水印YUV
     * @param string $imageFile 图片文件路径（png/jpg等）
     * @param string $outputFile 输出YUV文件路径
     * @param int|null $targetWidth 目标宽度（null则保持原尺寸）
     * @param int|null $targetHeight 目标高度
     * @return bool
     * @throws \RuntimeException
     */
    public static function generateFromImage(string $imageFile, string $outputFile, ?int $targetWidth = null, ?int $targetHeight = null): bool
    {
        if (!extension_loaded('gd')) {
            throw new \RuntimeException('GD扩展未安装，无法生成水印');
        }
        if (!file_exists($imageFile)) {
            throw new \RuntimeException("图片文件不存在: {$imageFile}");
        }

        $imgInfo = getimagesize($imageFile);
        if ($imgInfo === false) {
            throw new \RuntimeException("无法读取图片信息: {$imageFile}");
        }

        $srcW = $imgInfo[0];
        $srcH = $imgInfo[1];
        $type = $imgInfo[2];

        switch ($type) {
            case IMAGETYPE_PNG:
                $srcImg = imagecreatefrompng($imageFile);
                break;
            case IMAGETYPE_JPEG:
                $srcImg = imagecreatefromjpeg($imageFile);
                break;
            case IMAGETYPE_GIF:
                $srcImg = imagecreatefromgif($imageFile);
                break;
            default:
                throw new \RuntimeException("不支持的图片格式: {$type}");
        }

        if ($srcImg === false) {
            throw new \RuntimeException("加载图片失败: {$imageFile}");
        }

        $dstW = $targetWidth ?? $srcW;
        $dstH = $targetHeight ?? $srcH;

        if ($dstW === $srcW && $dstH === $srcH) {
            $dstImg = $srcImg;
        } else {
            $dstImg = imagecreatetruecolor($dstW, $dstH);
            if ($dstImg === false) {
                imagedestroy($srcImg);
                throw new \RuntimeException('创建目标图像失败');
            }
            imagecopyresampled($dstImg, $srcImg, 0, 0, 0, 0, $dstW, $dstH, $srcW, $srcH);
            imagedestroy($srcImg);
        }

        $yuvData = self::rgbImageToYuv420p($dstImg, $dstW, $dstH);
        imagedestroy($dstImg);

        $result = file_put_contents($outputFile, $yuvData);
        return $result !== false;
    }
